"""Writes src/hw/st7920_font.rs: half-width characters 0x20..0x7E for the
ST7920's text layer, 8x16 cells drawn from the X11 8x13 font (public
domain) with 2 blank rows above. The real HCGROM font differs in detail.

Usage: python3 tools/st7920_font.py
"""
import gzip
import os
from PIL import PcfFontFile

FONT = "/usr/share/fonts/X11/misc/8x13-ISO8859-1.pcf.gz"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "hw", "st7920_font.rs")

pcf = PcfFontFile.PcfFontFile(gzip.open(FONT))
lines = ["// Generated by tools/st7920_font.py from the X11 8x13 font (public domain).",
         "// Half-width characters 0x20..0x7E: 16 rows each, leftmost pixel in bit 7.",
         "pub const FIRST: u8 = 0x20;",
         "pub const GLYPHS: [[u8; 16]; 95] = ["]
for ch in range(0x20, 0x7F):
    rows = [0] * 16
    glyph = pcf.glyph[ch]
    if glyph:
        (_, _), (x0, y0, x1, y1), _, im = glyph
        top = 2 + 11 + y0                   # ascent 11, baseline at row 13
        for y in range(im.size[1]):
            for x in range(im.size[0]):
                if im.getpixel((x, y)):
                    rows[top + y] |= 0x80 >> (x0 + x)
    lines.append("    [" + ", ".join(f"0x{r:02x}" for r in rows) + f"], // {chr(ch)!r}")
lines.append("];")
open(OUT, "w").write("\n".join(lines) + "\n")
print(OUT)
