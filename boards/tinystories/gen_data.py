"""Generates data.inc for tinystories.asm: flash data read with FLASH_RD.

- The lookup tables and constants of tinystories/out/tables.inc (from
  tinystories/export.py), as plain RETLW lists: RSQRT (16-bit, index
  64..255), EXP2, SIGMOID (+128), SIN quarter wave (16-bit, 256 steps),
  FINAL_GAIN (16-bit), ROPE_INC0..3.
- The vocabulary as the LCD shows it: per token a length byte (VOCAB_LEN)
  and the text (VOCAB_TXT, all tokens back to back). Byte tokens <0xNN>
  become that byte if it is printable ASCII or a newline, else nothing;
  other non-ASCII characters become '?'.
- A 4x6 pixel font for ASCII 32..126 from the X11 4x6 font (public
  domain): per glyph 6 rows of 4 pixels, two rows per byte, high nibble
  first (FONT).

Usage: python3 gen_data.py   (after cd ../../tinystories && python3 export.py)
"""

import gzip
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TS = os.path.join(HERE, "..", "..", "tinystories")
sys.path.insert(0, TS)

from imgrun import parse_tables  # noqa: E402
from model import Tokenizer  # noqa: E402

FONT = "/usr/share/fonts/X11/misc/4x6-ISO8859-1.pcf.gz"


def dt_lines(label, values, comment):
    lines = [f"; {comment}", f"{label}:"]
    for i in range(0, len(values), 16):
        lines.append("\tdt\t" + ", ".join(f"0x{v & 0xFF:02X}" for v in values[i:i + 16]))
    return lines + [""]


def vocab():
    tok = Tokenizer()
    pieces = []
    for p in tok.vocab:
        if len(p) == 6 and p.startswith(b"<0x") and p.endswith(b">"):
            b = int(p[3:5], 16)
            p = bytes([b]) if (32 <= b < 127 or b == 10) else b""
        elif p in (b"<unk>", b"\n<s>\n", b"\n</s>\n"):
            p = b""
        else:
            p = bytes(c if (32 <= c < 127 or c == 10) else ord("?") for c in p.decode("utf-8").encode("ascii", "replace"))
        assert len(p) < 256
        pieces.append(p)
    return pieces


def font():
    from PIL import PcfFontFile
    f = PcfFontFile.PcfFontFile(gzip.open(FONT))
    out = []
    for ch in range(32, 127):
        rows = [0] * 6
        g = f.glyph[ch]
        if g is not None:
            im = g[3]                     # every glyph is a whole 4x6 cell
            for y in range(6):
                for x in range(4):
                    if im.getpixel((x, y)):
                        rows[y] |= 8 >> x
        out += [rows[0] << 4 | rows[1], rows[2] << 4 | rows[3], rows[4] << 4 | rows[5]]
    return out


def main():
    tabs, consts = parse_tables(os.path.join(TS, "out", "tables.inc"))
    lines = ["; Generated by gen_data.py. Do not edit.", ""]
    for j in range(4):
        lines.append(f"ROPE_INC{j}\tEQU\t0x{consts[f'ROPE_INC{j}']:06X}")
    lines.append("")
    lines += dt_lines("RSQRT_LO", tabs["RSQRT_LO"], "1/sqrt, index n' >> 8 - 64, low byte")
    lines += dt_lines("RSQRT_HI", tabs["RSQRT_HI"], "... high byte")
    lines += dt_lines("EXP2", tabs["EXP2"], "255 * 2^(-i/32)")
    lines += dt_lines("SIGMOID", tabs["SIGMOID"], "sigmoid((i + 0.5) / 8) * 256 - 128")
    lines += dt_lines("SIN_LO", tabs["SINA_LO"] + tabs["SINB_LO"], "sin quarter wave, Q14, 256 steps, low byte")
    lines += dt_lines("SIN_HI", tabs["SINA_HI"] + tabs["SINB_HI"], "... high byte")
    lines += dt_lines("FINAL_GAIN", tabs["FINAL_GAIN"], "final RMSNorm gain * log2(e), Q12, int16 little endian")
    pieces = vocab()
    lines += dt_lines("VOCAB_LEN", [len(p) for p in pieces], "length of each token's text")
    lines += dt_lines("VOCAB_TXT", list(b"".join(pieces)), "token text, back to back")
    lines += dt_lines("FONT", font(), "4x6 font, ASCII 32..126, 3 bytes per glyph")
    path = os.path.join(HERE, "data.inc")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{path}: {sum(len(p) for p in pieces)} bytes of token text")


if __name__ == "__main__":
    main()
